// Пример простой имитации связанного списка:

// Узел связанного списка
function Nodes(data) {
  this.data = data;
  this.next = null;
  console.log("Nodes() called with:", data);
}

// Создание узлов
const node_1 = new Nodes(1); // это функция-конструктор. Если вызвать её через new, она создаёт объект
const node_2 = new Nodes(2);
const node_3 = new Nodes(3);

// Связывание узлов
node_1.next = node_2;  // это “ссылка на объект”
node_2.next = node_3;

// Теперь у вас есть простой связанный список: 1 -> 2 -> 3

console.log("Связанный список: ", node_1.data, " -> ", node_2.data, " -> ", node_3.data);

console.log("node_1.next =", node_1.next);
console.log("node_1 =", node_1);

console.log("node_3.next =", node_3.next);
console.log("node_3 =", node_3);

/**
 * То есть получается структура:

node1 это объект-узел
node1.next указывает на объект node2
node2.next указывает на объект node3
node3.next это null

Это и есть имитация (реализация) связанного списка в JS.
связанный список в JS существует как “структура из объектов”, просто не как встроенный тип.
 */
/*
В этом примере `Node` - это конструктор, представляющий узел связанного списка. У каждого узла есть `data` (данные узла) и `next` (ссылка на следующий узел).

Однако, в реальных приложениях, если вам нужны сложные операции со связанными списками, рекомендуется использовать массивы (`Array`), так как они предоставляют более эффективные методы для работы с упорядоченными данными в JavaScript.
*/
/**
 * Массив это когда элементы лежат рядом в памяти, поэтому arr[i] работает мгновенно. Но если массив растет и рядом нет места, он может переехать в новый блок, поэтому push обычно быстрый, но иногда дорогой. Связанный список это цепочка узлов, каждый узел хранит значение и ссылку на следующий. Вставлять удобно, но чтобы найти i-й элемент, надо идти по ссылкам один за другим.
 */
/**
 * Главная мысль “массив vs связанный список” 

Массив: быстрый доступ по индексу O(1), но вставки/удаления в середине дорогие O(n), и иногда push может вызвать “переезд” (редко, но бывает). 

Связанный список: вставки/удаления рядом с известным узлом могут быть O(1), но доступ к элементу по позиции почти всегда O(n), плюс есть память на ссылки.

В реальном JS чаще используют массивы, потому что для типовых задач они быстрее и удобнее, а linked list чаще нужен как учебная модель и как кирпичик для других структур.
 */
/**
 * JavaScript не даёт встроенного типа данных LinkedList, но связанный список легко реализуется вручную: каждый узел это обычный объект с полями value и next, где next хранит ссылку на следующий объект. Когда мы делаем node1.next = node2, мы не “копируем” данные, а сохраняем ссылку на объект node2, поэтому получается цепочка node1 -> node2 -> node3 -> null.
 */
// Определение класса Node для связанного списка
class Node {
    constructor(value) {
        this.value = value;  // value это значение узла.
        this.next = null;  // next это ссылка на следующий узел (по смыслу это next, “address”).
    }
}
// class Node { ... }: создаёт объекты (синтаксис современнее, чем функция).
/**
 * Узел сам по себе не “список”. Список появляется, когда ты связываешь узлы ссылками.
 */

// Пример работы со связанным списком
const linkedListExample = () => {
    // Создание связанного списка
   
    const node1 = new Node(1);
    const node2 = new Node(2);
    const node3 = new Node(3);

    node1.next = node2;
    node2.next = node3;

    // Получается цепочка:  node1 -> node2 -> node3 -> null
    /**
     * Ключевой момент: узлы не обязаны лежать рядом в памяти. Каждый может быть “в своем ящике”, но в каждом узле хранится “адрес следующего”. Это противоположность массиву.
     */
    // Печать элементов связанного списка с разъяснениями
    let current = node1;
    let index = 1;
    while (current) {
        console.log(`node ${index} has value ${current.value}`);
        current = current.next;
        index++;
    }
};
/**
 * Тут супер важно: в связанном списке нет “индекса 2”. Чтобы добраться до третьего элемента, ты обязан пройти 1-й, потом 2-й, потом 3-й. То есть доступ “к i-му” обычно O(n).
 */

// Вызов примера для связанного списка
console.log("\nLinked List Example:");
linkedListExample();


/**
1. (medium)
215. Kth Largest Element in an Array
Почему: это лучший способ поговорить про “Big O = худший случай” (в лекции это выделено отдельно).
Quickselect в среднем близок к O(n), но в худшем может деградировать до O(n²), и вот это прям взрослая мысль: “среднее быстро, но worst-case опасный”.

2. (easy)
1. Two Sum
Почему: супер-наглядная демонстрация выбора алгоритма.
Брутфорс: O(n²)
Хэш-мапа: O(n) по времени (и платим памятью).
оптимизация по времени vs по памяти. 

3. (easy)
242. Valid Anagram
Почему: одна и та же задача решается двумя “скоростями”:
Сортировка строк: O(n log n)
Частоты (counting): O(n)
Это идеальный мостик к мысли “скорость не в секундах, а в росте числа операций”. 

4. (medium)
46. Permutations
Почему: это “мини-коммивояжёр” по ощущению. Количество вариантов растёт факториально: O(n!), и ты буквально видишь, как всё взрывается по мере роста n. Это та же идея, что в примере с коммивояжёром: перебор перестановок становится быстро невозможным.

5.
217. Contains Duplicate
Почему: идеальная демонстрация “наивно vs умно”.
брутфорс сравнивать всё со всем: O(n²)
set/hash: O(n) по времени (и память в обмен).
выбираешь алгоритм, думая про рост времени и про память.
 */